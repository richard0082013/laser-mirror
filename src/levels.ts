export type Level = {
  /** 名字和说明在 locales/ 里，按这个 id 查。 */
  id: string;
  grid: readonly string[];
  /** 过关最少要点几次，测试会核对。 */
  par: number;
  /** 这关能放几面镜子。 */
  inventory?: number;
  /** 第一次玩时在棋盘上标出什么：tap 是该点的格子，其余是要认识的新东西。 */
  teach?: 'tap' | 'target' | 'filter' | 'both' | 'portal' | 'switch' | 'oneway';
};

